export function translate(locale, key, values = {}) {
  const parts = key.split('.')
  let value = messages[locale] || messages.en
  for (const part of parts) value = value?.[part]
  if (typeof value === 'function') return value(values.count ?? values.name ?? values.agent ?? values.label)
  if (typeof value !== 'string') return key
  return value.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? '')
}

export const LocaleContext = createContext({ locale: 'en', setLocale: () => {}, t: translate.bind(null, 'en') })
export function useLocale() { return useContext(LocaleContext) }
export { messages }
